"""S1 acquisition, git side, against a real repository built in tmp_path and mirror-cloned."""

import datetime as dt
import os
import subprocess

import pytest
from s1 import repo

UTC = dt.UTC


def _run(cwd, *args, date="2026-01-01T00:00:00Z"):
    env = os.environ | {"GIT_AUTHOR_DATE": date, "GIT_COMMITTER_DATE": date, "GIT_CONFIG_GLOBAL": os.devnull}
    cmd = ["git", "-c", "user.name=t", "-c", "user.email=t@example.com", "-c", "commit.gpgsign=false", *args]
    return subprocess.run(cmd, cwd=cwd, env=env, check=True, capture_output=True).stdout.decode().strip()


def _commit(work, files, msg, date, remove=()):
    for path, content in files.items():
        p = work / path
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(content)
    for path in remove:
        _run(work, "rm", "-q", path)
    _run(work, "add", "-A")
    _run(work, "commit", "-q", "-m", msg, date=date)
    return _run(work, "rev-parse", "HEAD")


@pytest.fixture
def clone(tmp_path):
    """main: c1 (Jan 1) -> c2 (Mar 1). A PR branch off c1 with two commits, published only as
    refs/pull/7/head, as GitHub serves a fork PR. The mirror must carry it."""
    work = tmp_path / "work"
    work.mkdir()
    _run(work, "init", "-q", "-b", "main")
    c1 = _commit(
        work,
        {
            "app/core.py": b"def f():\n    return 1\n",
            "app/old.py": b"x = 1\n",
            "README.md": b"one two three four\n",
            "docs/guide.md": b"five six\nseven\n",
            "CHANGELOG.md": b"not counted at all\n",
            "tests/test_core.py": b"def test(): pass\n",
            "big.go": b"package big\n" * 61,
            "gen.go": b"// Code generated by protoc. DO NOT EDIT.\npackage gen\n",  # step 5, by content
            "blob.py": b"\xff\xfe\n",  # step 7, not UTF-8
        },
        "c1",
        "2026-01-01T00:00:00Z",
    )
    (work / "link.py").symlink_to("app/core.py")
    c2 = _commit(work, {"later.py": b"y = 2\n"}, "c2", "2026-03-01T00:00:00Z")
    _run(work, "checkout", "-q", "-b", "pr", c1)
    _run(work, "mv", "app/old.py", "app/renamed.py")
    p1 = _commit(work, {"app/core.py": b"def f():\n    return 2\n"}, "p1", "2026-01-05T00:00:00Z")
    p2 = _commit(work, {"app/new.py": b"z = 3\n"}, "p2", "2026-01-06T00:00:00Z")
    _run(work, "update-ref", "refs/pull/7/head", p2)
    _run(work, "checkout", "-q", "main")
    _run(work, "branch", "-q", "-D", "pr")
    git_dir = repo.mirror(f"file://{work}", tmp_path / "mirror.git")
    return {"git": git_dir, "c1": c1, "c2": c2, "p1": p1, "p2": p2, "work": work}


def test_the_mirror_carries_pull_refs_so_fork_commits_resolve(clone):
    assert repo.base_commit(clone["git"], clone["p1"]) == (clone["c1"], None)


def test_an_unresolvable_base_is_a_reason_not_a_guess(clone):
    assert repo.base_commit(clone["git"], "f" * 40) == (None, "first commit not in the clone")
    assert repo.base_commit(clone["git"], clone["c1"]) == (None, "first commit has no parent")


def test_the_as_of_commit_is_the_last_one_before_the_instant(clone):
    g = clone["git"]
    assert repo.as_of_commit(g, "main", dt.datetime(2026, 2, 1, tzinfo=UTC)) == clone["c1"]
    assert repo.as_of_commit(g, "main", dt.datetime(2026, 4, 1, tzinfo=UTC)) == clone["c2"]
    assert repo.as_of_commit(g, "main", dt.datetime(2025, 1, 1, tzinfo=UTC)) is None


def test_the_as_of_commit_follows_the_first_parent_only(clone):
    # A side branch's commit (Mar 5) is merged into main on Mar 20. At Mar 10, main was still c2.
    g, work = clone["git"], clone["work"]
    _run(work, "checkout", "-q", "-b", "side", clone["c2"])
    _commit(work, {"side.py": b"s = 1\n"}, "side", "2026-03-05T00:00:00Z")
    _run(work, "checkout", "-q", "main")
    _run(work, "merge", "-q", "--no-ff", "--no-edit", "side", date="2026-03-20T00:00:00Z")
    subprocess.run(["git", "--git-dir", str(g), "fetch", "-q", "origin", "+refs/*:refs/*"], check=True)
    assert repo.as_of_commit(g, "main", dt.datetime(2026, 3, 10, tzinfo=UTC)) == clone["c2"]


def test_measure_applies_the_seven_step_universe_and_counts_markdown(clone):
    m = repo.measure(clone["git"], clone["c1"])
    # In: app/core.py, app/old.py, README.md, docs/guide.md, big.go (61 lines -> 2 chunks).
    # Out: CHANGELOG.md (markdown), tests/ (test), gen.go (generated header),
    # blob.py (not UTF-8). The symlink arrives in c2, so it is not here.
    assert m == repo.Measure(file_count=5, chunk_estimate=1 + 1 + 1 + 1 + 2, md_files=2, md_words=7)
    m2 = repo.measure(clone["git"], clone["c2"])
    assert m2.file_count == 6  # later.py is in; link.py is a symlink and is not


def test_changed_files_carry_their_base_path_mode_and_bytes(clone):
    got = {c.path: c for c in repo.changed(clone["git"], clone["c1"], clone["p2"])}
    assert set(got) == {"app/core.py", "app/renamed.py", "app/new.py"}
    assert got["app/core.py"].base_bytes == b"def f():\n    return 1\n"
    assert got["app/core.py"].base_mode == "100644"
    assert got["app/renamed.py"].previous_path == "app/old.py"
    assert got["app/renamed.py"].base_bytes == b"x = 1\n"
    assert got["app/new.py"].base_mode is None and got["app/new.py"].base_bytes is None


def test_a_merge_inside_the_pr_range_is_detected(clone):
    g, work = clone["git"], clone["work"]
    assert not repo.has_merges(g, clone["c1"], clone["p2"])
    _run(work, "checkout", "-q", "-b", "pr2", clone["p2"])
    _run(work, "merge", "-q", "--no-edit", "main", date="2026-03-02T00:00:00Z")
    _run(work, "update-ref", "refs/pull/8/head", "HEAD")
    subprocess.run(["git", "--git-dir", str(g), "fetch", "-q", "origin", "+refs/*:refs/*"], check=True)
    assert repo.has_merges(g, clone["c1"], "refs/pull/8/head")


def test_reads_leave_the_clone_unchanged(clone):
    g = clone["git"]
    before = subprocess.run(["git", "--git-dir", str(g), "show-ref"], capture_output=True).stdout
    repo.measure(g, clone["c2"])
    repo.changed(g, clone["c1"], clone["p2"])
    repo.base_commit(g, clone["p1"])
    assert subprocess.run(["git", "--git-dir", str(g), "show-ref"], capture_output=True).stdout == before


def test_amendment_1_accepts_a_linear_pr(clone):
    assert repo.resolve(clone["git"], clone["p1"], clone["p2"]) == (clone["c1"], None)


def test_amendment_1_excludes_a_pr_with_an_internal_merge(clone):
    g, work = clone["git"], clone["work"]
    _run(work, "checkout", "-q", "-b", "pr9", clone["p2"])
    _run(work, "merge", "-q", "--no-ff", "--no-edit", "main", date="2026-03-02T00:00:00Z")
    tip = _commit(work, {"app/after.py": b"w = 4\n"}, "after the merge", "2026-03-03T00:00:00Z")
    _run(work, "update-ref", "refs/pull/9/head", tip)
    subprocess.run(["git", "--git-dir", str(g), "fetch", "-q", "origin", "+refs/*:refs/*"], check=True)
    assert repo.resolve(g, clone["p1"], tip) == (clone["c1"], "merge_commit_in_pr_history")


def test_an_unresolved_base_keeps_its_s1_3_reason_before_amendment_1(clone):
    assert repo.resolve(clone["git"], "f" * 40, clone["p2"]) == (None, "first commit not in the clone")

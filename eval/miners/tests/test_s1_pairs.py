"""S1's pair filters (ADR-0013 D-2, D-3) and manifest count checks."""

import datetime as dt

import pytest
from s1 import manifest, pairs

GEN = b"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n"


def _ch(path, mode="100644", content=b"x\n", previous=None):
    return pairs.Changed(path=path, previous_path=previous, base_mode=mode, base_bytes=content)


def test_gold_files_are_source_files_in_the_universe():
    changed = [
        _ch("app/core.py"),
        _ch("app/cli.go"),
        _ch("docs/usage.md"),
        _ch("tests/test_core.py"),
        _ch("go.sum"),
        _ch("api/x.go", content=GEN),
    ]
    assert pairs.gold_files(changed) == ["app/cli.go", "app/core.py"]


def test_gold_labels_are_verified_against_the_base_snapshot():
    # Review of #50: the label is the file as it was at the pre-fix base commit.
    assert pairs.gold_files([_ch("app/new.py", mode=None, content=None)]) == []  # added: not at base
    assert pairs.gold_files([_ch("new/x.py", previous="old/x.py")]) == ["old/x.py"]  # a rename: old path
    assert pairs.gold_files([_ch("src/x.py", previous="tests/x.py")]) == []  # judged at the base path
    assert pairs.gold_files([_ch("app/link.py", mode="120000")]) == []  # a symlink at base
    assert pairs.gold_files([_ch("api/x.go", content=GEN)]) == []  # generated at base
    assert pairs.gold_files([_ch("app/x.py", content=b"\xff\xfe")]) == []  # invalid UTF-8 at base
    assert pairs.gold_files([_ch("app/x.py", content=None)]) == []  # base bytes unread


@pytest.mark.parametrize(
    "n,cap,kept,why",
    [
        (0, 10, False, "no source files"),
        (1, 10, True, None),
        (10, 10, True, None),
        (11, 10, False, "more than 10 source files"),
        (11, 15, True, None),
    ],
)
def test_d2_drops_pairs_with_0_or_too_many_source_files(n, cap, kept, why):
    assert pairs.keep([f"f{i}.py" for i in range(n)], max_files=cap) == (kept, why)


def test_d3_an_issue_edited_after_the_merge_is_weak():
    merged = dt.datetime(2026, 1, 1, tzinfo=dt.UTC)
    assert pairs.weak(merged + dt.timedelta(seconds=1), merged)
    assert not pairs.weak(merged, merged)


@pytest.mark.parametrize(
    "pf,why",
    [
        ({"total_count": 10, "strong_count": 7, "weak_count": 3}, None),
        (
            {"total_count": 10, "strong_count": 7, "weak_count": 2},
            "total_count 10 != strong_count 7 + weak_count 2",
        ),
        ({"total_count": 10, "strong_count": 10}, "weak_count missing"),
        (
            {"total_count": -1, "strong_count": -1, "weak_count": 0},
            "strong_count is not a non-negative integer",
        ),
    ],
)
def test_the_manifest_counts_are_explicit_and_add_up(pf, why):
    # Review of #50: `count` was ambiguous; total = strong + weak is checked, never assumed.
    assert manifest.count_problem(pf) == why

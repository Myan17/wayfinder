"""S1's file universe and chunk estimate (ADR-0016)."""

import pytest
from s1 import universe

GEN = b"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n"


@pytest.mark.parametrize(
    "path,mode,content,why",
    [
        ("a/b.py", "100644", b"x\n", None),
        ("cmd/x.go", "100755", b"x\n", None),
        ("docs/guide.md", "100644", b"x\n", None),
        ("link.py", "120000", b"", "not a regular file"),  # step 1: symlink
        ("setup.cfg", "100644", b"x\n", "extension"),  # step 2
        ("tests/test_app.py", "100644", b"x\n", "test"),  # step 3: directory
        ("src/app_test.go", "100644", b"x\n", "test"),  # step 3: filename
        ("src/conftest.py", "100644", b"x\n", "test"),
        ("testdata/README.md", "100644", b"x\n", "test"),  # test Markdown too (S1-4)
        ("vendor/x/y.go", "100644", b"x\n", "vendored"),  # step 4
        ("api/x_pb2.py", "100644", b"x\n", "generated"),  # step 5: name
        ("api/x.go", "100644", GEN, "generated"),  # step 5: Go header
        ("CHANGELOG.md", "100644", b"x\n", "markdown"),  # step 6
        ("docs/LICENSE.md", "100644", b"x\n", "markdown"),
        (".github/CONTRIBUTING.md", "100644", b"x\n", "markdown"),
        ("a/b.py", "100644", b"\xff\xfe", "binary"),  # step 7
    ],
)
def test_the_file_universe_is_adr_0016s_seven_steps(path, mode, content, why):
    assert universe.excluded(path, mode, content) == why


def test_the_go_header_only_counts_in_the_first_ten_lines():
    late = b"package x\n" * 10 + b"// Code generated by x. DO NOT EDIT.\n"
    assert universe.excluded("a.go", "100644", late) is None


def test_lines_and_chunks_are_byte_exact():
    assert universe.lines(b"") == 0 and universe.chunks(b"") == 0
    assert universe.lines(b"a\nb\n") == 2
    assert universe.lines(b"a\nb") == 2  # no final newline: +1
    assert universe.chunks(b"x\n" * 60) == 1 and universe.chunks(b"x\n" * 61) == 2

def _git(cwd, *args):
    env = os.environ | {
        "GIT_CONFIG_GLOBAL": os.devnull,
        "GIT_AUTHOR_DATE": "2026-01-01T00:00:00Z",
        "GIT_COMMITTER_DATE": "2026-01-01T00:00:00Z",
    }
    cmd = ["git", "-c", "user.name=t", "-c", "user.email=t@example.com", "-c", "commit.gpgsign=false", *args]
    return subprocess.run(cmd, cwd=cwd, env=env, check=True, capture_output=True).stdout.decode().strip()


@pytest.fixture
def snap(tmp_path):
    """One commit holding every kind of file the universe keeps or drops, mirror-cloned."""
    work = tmp_path / "work"
    work.mkdir()
    _git(work, "init", "-q", "-b", "main")
    files = {
        "app/core.py": b"".join(b"line %d\n" % i for i in range(1, 122)),  # 121 lines: 3 windows
        "app/tail.py": b"a\nb",  # no final newline: 2 lines, 1 window
        "app/empty.py": b"",  # 0 lines, 0 windows
        "docs/guide.md": b"caf\xc3\xa9\n",
        "CHANGELOG.md": b"dropped\n",
        "tests/test_core.py": b"dropped\n",
        "gen.go": b"// Code generated by x. DO NOT EDIT.\npackage gen\n",
        "blob.py": b"\xff\xfe\n",
    }
    for path, content in files.items():
        (work / path).parent.mkdir(parents=True, exist_ok=True)
        (work / path).write_bytes(content)
    _git(work, "add", "-A")
    _git(work, "commit", "-q", "-m", "c1")
    commit = _git(work, "rev-parse", "HEAD")
    return repo.mirror(str(work), tmp_path / "mirror.git"), commit


def test_windows_are_60_line_cuts_with_a_shorter_last_window(snap):
    git_dir, commit = snap
    ws = inputs.snapshot(git_dir, commit, 7)
    assert [(w.path, w.index, w.first_line) for w in ws] == [
        ("app/core.py", 0, 1),
        ("app/core.py", 1, 61),
        ("app/core.py", 2, 121),
        ("app/tail.py", 0, 1),
        ("docs/guide.md", 0, 1),
    ]
    core = [w.text for w in ws if w.path == "app/core.py"]
    assert core[0].count("\n") == 60 and core[0].startswith("line 1\n")
    assert core[2] == "line 121\n"
    assert ws[3].text == "a\nb" and ws[4].text == "café\n"


def test_the_window_count_is_eval_datas_own_chunk_estimate(snap):
    git_dir, commit = snap
    assert len(inputs.snapshot(git_dir, commit, 7)) == repo.measure(git_dir, commit).chunk_estimate == 5


def test_line_split_matches_universe_lines():
    for content in (b"", b"\n", b"a", b"a\n", b"a\n\nb", b"\n\n\n"):
        assert len(inputs.split_lines(content)) == universe.lines(content)
        assert b"".join(inputs.split_lines(content)) == content


def test_count_problems_refuses_any_difference_from_the_manifest():
    manifest = {
        "selected": [1, 2],
        "candidates": [
            {"github_repo_id": 1, "chunk_estimate": 10},
            {"github_repo_id": 2, "chunk_estimate": 5},
            {"github_repo_id": 3, "chunk_estimate": 9},
        ],
    }
    assert inputs.count_problems({1: 10, 2: 5}, manifest) == []
    assert inputs.count_problems({1: 10, 2: 4}, manifest) == ["2: 4 windows, manifest chunk_estimate 5"]
    assert inputs.count_problems({1: 10}, manifest) == ["2: None windows, manifest chunk_estimate 5"]
    assert inputs.count_problems({1: 10, 2: 5, 3: 9}, manifest) == ["3: not a selected repository"]


def test_the_committed_manifest_estimates_sum_to_7175():
    m = json.loads(MANIFEST.read_text())
    est = {c["github_repo_id"]: c["chunk_estimate"] for c in m["candidates"]}
    assert sum(est[r] for r in m["selected"]) == 7175


def test_pseudo_repo_is_amendment_1s_exact_hash():
    expected = int(hashlib.sha256(b"90194616/pydantic/main.py").hexdigest(), 16) % 100
    assert inputs.pseudo_repo(90194616, "pydantic/main.py") == expected
    assert inputs.pseudo_repo(1, "é.py") == int(hashlib.sha256("1/é.py".encode()).hexdigest(), 16) % 100


def test_a_files_windows_share_one_pseudo_repo(snap):
    git_dir, commit = snap
    ws = [w for w in inputs.snapshot(git_dir, commit, 7) if w.path == "app/core.py"]
    assert {w.pseudo_repo for w in ws} == {inputs.pseudo_repo(7, "app/core.py")}


def test_grant_levels_are_0_then_0_to_9_then_0_to_99():
    assert {k: (v.start, v.stop) for k, v in inputs.GRANTS.items()} == {1: (0, 1), 10: (0, 10), 100: (0, 100)}
    ws = [inputs.Window(1, f"f{i}", 0, 1, "", i) for i in range(100)]
    assert [inputs.admitted_fraction(ws, p) for p in (1, 10, 100)] == [0.01, 0.10, 1.0]


def test_the_strong_dev_query_set_is_874_issues():
    pairs = [json.loads(line) for line in PAIRS.read_text().splitlines()]
    issues = inputs.strong_dev_issues(pairs)
    assert len(issues) == 874
    assert issues == sorted(issues, key=lambda q: (q.github_repo_id, q.issue))
    keep = {(p["github_repo_id"], p["issue"]) for p in pairs if p["strong"] and p["split"] == "dev"}
    assert {(q.github_repo_id, q.issue) for q in issues} == keep


def test_weak_and_non_dev_pairs_are_excluded_and_a_split_group_is_refused():
    base = {"github_repo_id": 1, "issue": 5, "group_id": "1:9", "strong": True, "split": "dev"}
    assert inputs.strong_dev_issues([base | {"strong": False}, base | {"split": "test"}]) == []
    assert len(inputs.strong_dev_issues([base, base | {"pr": 2}])) == 1
    with pytest.raises(ValueError, match="two groups"):
        inputs.strong_dev_issues([base, base | {"group_id": "1:10"}])


def test_normalization_is_nfc_and_trailing_whitespace_only():
    assert inputs.normalize('café  \nx\t\n  indented "a  b"  ') == 'café\nx\n  indented "a  b"'
    assert inputs.query_text("Title", None) == "Title"
    assert inputs.query_text("Title", "Body") == "Title\n\nBody"


def test_queries_above_2000_characters_are_rejected():
    assert inputs.accepted("x" * 2000) and not inputs.accepted("x" * 2001)


def test_the_cold_sample_is_the_first_of_each_of_the_first_50_groups():
    issues = [inputs.Issue(1, n, f"1:{n // 2}") for n in range(200)]  # two issues per group
    sample = inputs.cold_sample(reversed(issues))
    assert len(sample) == 50 and len({q.group_id for q in sample}) == 50
    order = sorted({q.group_id for q in issues}, key=lambda g: hashlib.sha256(g.encode()).hexdigest())
    assert [q.group_id for q in sample] == order[:50]
    assert all(q.issue % 2 == 0 for q in sample)  # the lower issue number of each group
